/**
 * Filter values for the BWB search, copied from the appendices of the SRU BWB
 * manual ("Handleiding SRU BWB": Waardelijst Regelingsoort,
 * Eerstverantwoordelijke and Rechtsgebied). The values are sent to the service
 * as is and also appear in the URL.
 */

export type SearchOption = { value: string; label: string };

/** Removes duplicates and sorts the values in Dutch order. */
function toOptions(
  values: string[],
  label: (value: string) => string,
): SearchOption[] {
  return [...new Set(values)]
    .sort((a, b) => a.localeCompare(b, "nl"))
    .map((value) => ({ value, label: label(value) }));
}

/** Capitalises the first letter: "justitie en veiligheid" becomes "Justitie en veiligheid". */
export function capitalize(value: string): string {
  return value.charAt(0).toUpperCase() + value.slice(1);
}

