// Generates src/api/xmlSchema.gen.ts from src/api/types.gen.ts.
//
// The TypeScript types only exist at compile time, but mapping XML onto them
// needs to know at runtime which fields are arrays, which are nested objects and
// which are primitives. This script extracts that information from the
// generated types so the XML mapper can stay generic.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const input = resolve(root, 'src/api/types.gen.ts');
const output = resolve(root, 'src/api/xmlSchema.gen.ts');

const source = readFileSync(input, 'utf8').replace(/\r\n/g, '\n');

const enums = new Set();
for (const match of source.matchAll(/^export type (\w+) = (-?\d+(?: \| -?\d+)*);$/gm)) {
    enums.add(match[1]);
}

const objectTypes = new Map();
for (const match of source.matchAll(/^export type (\w+) = \{\n([\s\S]*?)^\};$/gm)) {
    const [, name, body] = match;
    if (name.endsWith('Writable')) continue;
    const fields = [];
    for (const line of body.split('\n')) {
        const field = line.match(/^\s+(?:readonly )?(\w+)\??: (.+);$/);
        if (field) fields.push([field[1], field[2]]);
    }
    objectTypes.set(name, fields);
}

function describe(typeExpression) {
    let expr = typeExpression.replace(/ \| null$/, '').trim();
    let array = false;
    const arrayMatch = expr.match(/^Array<(.+)>$/);
    if (arrayMatch) {
        array = true;
        expr = arrayMatch[1];
    }
    let kind;
    if (expr === 'string' || expr.startsWith('`')) kind = 'string';
    else if (expr === 'number') kind = 'number';
    else if (expr === 'boolean') kind = 'boolean';
    else if (enums.has(expr)) kind = 'enum';
    else if (objectTypes.has(expr)) kind = expr;
    else kind = 'unknown';
    return array ? [kind, 1] : [kind];
}

const schema = {};
for (const [name, fields] of objectTypes) {
    schema[name] = Object.fromEntries(fields.map(([field, type]) => [field, describe(type)]));
}

const header = `// This file is auto-generated by scripts/generate-xml-schema.mjs. Do not edit.

/**
 * Field descriptor: [kind, isArray?]. Kind is a primitive ('string', 'number',
 * 'boolean', 'enum', 'unknown') or the name of another type in this schema.
 */
export type FieldDescriptor = readonly [kind: string, array?: 1];

export type TypeDescriptor = Readonly<Record<string, FieldDescriptor>>;

`;

writeFileSync(
    output,
    `${header}export const xmlSchema: Readonly<Record<string, TypeDescriptor>> = ${JSON.stringify(schema)};\n`,
);

console.log(`Wrote ${objectTypes.size} types to ${output}`);
